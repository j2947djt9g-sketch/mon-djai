const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const {canonicalEngine, root} = require('../../tools/clair/test-support/vm-loader.cjs');
const E = canonicalEngine();
const box = {ClairEngine:E,structuredClone};
vm.createContext(box);
for (const file of ['budget-commands','budget-session']) vm.runInContext(fs.readFileSync(root+'/clair/application/'+file+'.js','utf8'),box);
const original = E.empty();
original.openingCents = 100;
const session = box.ClairBudgetSession.create({owner:'account-a',epoch:1,budget:original});
const context = {owner:'account-a',epoch:1};
original.openingCents = 999;
assert.equal(session.getSnapshot().openingCents,100);
const snapshot=session.getSnapshot();snapshot.openingCents=888;
assert.equal(session.getSnapshot().openingCents,100);
let changes=0,captured,persisted;
const unsubscribe=session.subscribe(next=>{changes++;next.openingCents=777;});
assert.equal(session.commit(d=>{captured=d;d.openingCents+=1;},{context,persist:d=>{persisted=d;return 'durable';}}),'durable');
captured.openingCents=555;persisted.openingCents=444;
assert.equal(session.getSnapshot().openingCents,101);
assert.equal(changes,1);
let writes=0;
assert.throws(()=>session.commit(d=>{d.openingCents=200;},{context,persist:()=>{writes++;throw Error('quota');}}),/quota/);
assert.equal(session.getSnapshot().openingCents,101);
assert.equal(changes,1);
session.setOwner({owner:'account-b',epoch:2,budget:E.empty()});
assert.throws(()=>session.adoptRemote(original,context),/contexte/);
assert.throws(()=>session.commit(()=>{},{context,persist:()=>writes++}),/contexte/);
assert.equal(session.getSnapshot().openingCents,0);
const b={owner:'account-b',epoch:2};
session.adoptRemote(original,b);original.openingCents=12;
assert.equal(session.getSnapshot().openingCents,999);
assert.throws(()=>session.adoptRemote(E.empty(),{owner:'account-b',epoch:1}),/contexte/);
assert.throws(()=>session.commit(()=>session.setOwner({owner:'account-c',epoch:3,budget:E.empty()}),{context:b,persist:()=>writes++}),/contexte/);
assert.equal(writes,1,'stale preparation never persists');
const mutableContext={owner:'account-c',epoch:3};
assert.throws(()=>session.commit(d=>{
  d.openingCents=777;
  session.setOwner({owner:'account-d',epoch:4,budget:E.empty()});
  mutableContext.owner='account-d';mutableContext.epoch=4;
},{context:mutableContext,persist:()=>writes++}),/contexte/);
assert.equal(writes,1,'mutating a caller-owned context cannot authorize a stale draft');
unsubscribe();session.dispose();
assert.throws(()=>session.commit(()=>{},{context:{owner:'account-d',epoch:4},persist:()=>{}}),/fermée/);
console.log('PASS session: isolated references, durable commit, quota rollback, owner/epoch fencing, remote adoption, disposal');
