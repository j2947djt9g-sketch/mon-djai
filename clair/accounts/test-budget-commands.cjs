const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const {canonicalEngine, root} = require('../../tools/clair/test-support/vm-loader.cjs');
const E = canonicalEngine();
const context = {ClairEngine:E, structuredClone};
vm.createContext(context);
vm.runInContext(fs.readFileSync(root+'/clair/application/budget-commands.js','utf8'),context);
const prepare = context.ClairBudgetCommands.prepareBudgetChange;
const budget = E.empty();
budget.initialized = budget.setupDone = true;
budget.openingCents = 10000;
budget.openingBalanceDate = E.today();
const before = JSON.stringify(budget);
let captured;
const candidate = prepare(budget, draft => {
  captured = draft;
  draft.transactions.push({id:'manual',type:'expense',amountCents:123,date:E.today(),categoryId:'autre',name:'Test'});
});
assert.equal(E.balance(candidate),9877);
assert.equal(JSON.stringify(budget), before);
captured.transactions[0].amountCents = 500;
assert.equal(candidate.transactions[0].amountCents,123,'callback references cannot mutate the prepared result');
assert.throws(()=>prepare(budget,d=>{d.transactions.push({id:'bad',type:'expense',amountCents:0.5,date:E.today()});}),/Montant/);
assert.throws(()=>prepare(budget,async d=>{d.openingCents=1;}),/synchrone/);
assert.throws(()=>prepare(budget,()=>({then(){}})),/synchrone/);
assert.equal(JSON.stringify(budget),before);
const historical=prepare(budget,d=>{d.transactions.push({id:'old',type:'expense',amountCents:123,date:E.addDays(E.today(),-1)});});
const future=prepare(budget,d=>{d.transactions.push({id:'future',type:'expense',amountCents:321,date:E.addDays(E.today(),1)});});
assert.equal(E.balance(historical),9877);
assert.equal(E.balance(future),10000);
assert.throws(()=>prepare(budget,d=>{d.transactions.push({id:'express',type:'expense',amountCents:123,date:E.today(),express:{source:'express'}});}),/Express/);
assert.throws(()=>context.ClairBudgetCommands.validateBudgetCandidate({...budget,openingCents:0.5}),/Montant/);
console.log('PASS commands: isolated drafts, integer validation, sync-only callbacks, old/future dates, Express metadata');
